/**
 * راه‌اندازی دو کادر کشویی وابسته‌ی استان/شهرستان.
 * provinceSelectId: آی‌دی select استان
 * countySelectId: آی‌دی select شهرستان
 * selectedProvince / selectedCounty: مقادیر اولیه (برای پیش‌پرکردن فرم، مثلاً ویرایش سفارش)
 */
function initIranProvinceCountySelect(provinceSelectId, countySelectId, selectedProvince, selectedCounty) {
  const provinceSelect = document.getElementById(provinceSelectId);
  const countySelect = document.getElementById(countySelectId);
  if (!provinceSelect || !countySelect) return;

  const data = window.IRAN_PROVINCES_COUNTIES;

  function fillProvinces() {
    provinceSelect.innerHTML = '<option value="">انتخاب استان...</option>';
    Object.keys(data).forEach((province) => {
      const opt = document.createElement('option');
      opt.value = province;
      opt.textContent = province;
      if (province === selectedProvince) opt.selected = true;
      provinceSelect.appendChild(opt);
    });
  }

  function fillCounties(province, preselect) {
    countySelect.innerHTML = '<option value="">انتخاب شهرستان...</option>';
    const counties = data[province] || [];
    countySelect.disabled = counties.length === 0;
    counties.forEach((county) => {
      const opt = document.createElement('option');
      opt.value = county;
      opt.textContent = county;
      if (county === preselect) opt.selected = true;
      countySelect.appendChild(opt);
    });
  }

  fillProvinces();
  if (selectedProvince) {
    fillCounties(selectedProvince, selectedCounty);
  } else {
    countySelect.disabled = true;
  }

  provinceSelect.addEventListener('change', function () {
    fillCounties(provinceSelect.value, null);
  });
}
